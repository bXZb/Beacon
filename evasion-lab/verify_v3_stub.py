LEAVE = 0x7FF800000C194
GADGET = 0x7FF800009A050
SSN = 0x3A


def build(arity):
    s = arity - 4 if arity > 4 else 0
    assert s <= 7
    d = bytearray(V3TMPL[:0x19])
    d += V3TMPL[0x19:0x19 + 9 * s]
    t = len(d)
    d += V3TMPL[0x58:]
    d[0x0D:0x0D + 8] = struct.pack("<Q", LEAVE)
    for k, v in enumerate((LEAVE, GADGET, LEAVE, GADGET)):
        d[t + 0x02 + 15 * k:t + 0x02 + 15 * k + 8] = struct.pack("<Q", v)
    d[t + 0x40:t + 0x44] = struct.pack("<I", SSN)
    d[t + 0x4A:t + 0x52] = struct.pack("<Q", GADGET)
    return bytes(d), t


def main():
    fails = 0
    for arity in (4, 5, 6, 7, 11):
        s = max(0, arity - 4)
        b, t = build(arity)
        print("== arity %d (S=%d) len=%d" % (arity, s, len(b)))
        txt = ["%s %s" % (i.mnemonic, i.op_str) for i in md.disasm(b, 0x4000)]
        loads = [g for g in txt if g.startswith("mov rax, qword ptr [rbp + 0x")]
        stores = [g for g in txt if g.startswith("mov qword ptr [rsp + 0x")]
        fakes = [g for g in stores if any(("rsp + 0x%x" % a) in g for a in (0x60, 0x68, 0x70, 0x78))]
        ok = (txt[0] == "push rbp" and len(fakes) == 4
              and "mov r10, rcx" in txt and ("mov eax, %#x" % SSN) in txt
              and "jmp qword ptr [rip]" in txt and len(b) <= 256)
        print("   loads=%d stores=%d fakes=%d ok=%s" % (len(loads), len(stores), len(fakes), ok))
        if not ok:
            fails += 1
            for g in txt:
                print("     ", g)
    assert V3TMPL[0x00] == 0x55 and V3TMPL[0x04:0x07] == b"\x48\x81\xEC"
    assert V3TMPL[0x0B:0x0D] == b"\x48\xB8"
    assert V3TMPL[0x94:0x97] == b"\x4C\x8B\xD1"
    assert V3TMPL[0x97] == 0xB8 and V3TMPL[0x9C:0x9E] == b"\xFF\x25"
    print("template static offsets: OK")
    print("FAILURES:", fails)
    raise SystemExit(1 if fails else 0)


if __name__ == "__main__":
    main()
