#!/usr/bin/env python3
"""Generate or verify layout.h from a linked Windows DLL.

CMake owns compile and link. This script only parses the PE and writes
layout.h (pass-1 DLL) or checks that a later DLL matches the table.
"""
import argparse
import os
import struct
import sys

LAYOUT_EXCLUDE = {
    ".pdata", ".fptable", ".reloc", ".gfids", ".retplne",
    "_RDATA", ".idata", ".edata", ".debug",
}


def compute_regions(dll_bytes):
    lf = struct.unpack_from("<I", dll_bytes, 0x3C)[0]
    nsec = struct.unpack_from("<H", dll_bytes, lf + 6)[0]
    optsz = struct.unpack_from("<H", dll_bytes, lf + 20)[0]
    soi = struct.unpack_from("<I", dll_bytes, lf + 24 + 56)[0]
    regions = [(0, 0x1000)]
    for i in range(nsec):
        off = lf + 24 + optsz + i * 40
        name = dll_bytes[off:off + 8].rstrip(b"\0").decode(errors="replace")
        vsz, va, rsz, rp = struct.unpack_from("<IIII", dll_bytes, off + 8)
        chars = struct.unpack_from("<I", dll_bytes, off + 36)[0]
        if name in LAYOUT_EXCLUDE or (chars & 0x02000000):
            continue
        if va < 0x1000 or vsz == 0:
            continue
        ve = min(va + vsz, soi)
        regions.append((va, ve))
    return regions, soi


def write_layout_h(path, regions, soi):
    n = 16
    lines = [
        "#pragma once",
        "/* AUTO-GENERATED by tools/llvm/apply_layout.py */",
        f"#define BW_LAYOUT_SOI        0x{soi:06X}ULL",
        "#define BW_LAYOUT_REG_MAX    %d" % n,
        "static const unsigned long long bw_layout_reg[BW_LAYOUT_REG_MAX][2] = {",
    ]
    for i in range(n):
        if i < len(regions):
            a, b = regions[i]
            lines.append(f"    {{0x{a:X}ULL, 0x{b:X}ULL}},")
        else:
            lines.append("    {0ULL, 0ULL},")
    lines.append("};")
    lines.append(f"static const unsigned long long bw_layout_reg_n = {len(regions)}ULL;")
    body = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    return body


def verify_layout(dll_path, layout_h_path):
    regions, soi = compute_regions(open(dll_path, "rb").read())
    cur = open(layout_h_path, encoding="utf-8").read()
    ok = all(f"{{0x{a:X}ULL, 0x{b:X}ULL}}," in cur for a, b in regions)
    ok = ok and f"bw_layout_reg_n = {len(regions)}ULL" in cur
    ok = ok and f"BW_LAYOUT_SOI        0x{soi:06X}ULL" in cur
    return ok, len(regions), soi


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dll", required=True)
    ap.add_argument("--layout", required=True)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write-only", action="store_true",
                      help="write layout.h from --dll (pass-1)")
    mode.add_argument("--verify", action="store_true",
                      help="require --dll to match existing layout.h")
    args = ap.parse_args()

    if args.write_only:
        regions, soi = compute_regions(open(args.dll, "rb").read())
        write_layout_h(args.layout, regions, soi)
        print(f"==> wrote {args.layout} regions={len(regions)} soi=0x{soi:X}")
        return 0

    ok, n, soi = verify_layout(args.dll, args.layout)
    if not ok:
        print(f"layout mismatch dll={args.dll} layout={args.layout} "
              f"regions={n} soi=0x{soi:X}", file=sys.stderr)
        return 1
    print(f"==> layout verified ({os.path.getsize(args.dll)} bytes, {n} regions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
